//! Club finances: what goes into the package, and what is restored after OFM builds the world.
//!
//! OFM derives `transfer_budget` (15 % of the balance), `wage_budget` (from the wage bill and
//! reputation) and `stadium_capacity` (random) itself. The package format cannot carry them, so
//! they are restored on the built world -- only when the source has a value *and* it is
//! compatible. Every club/field is recorded with its provenance.
//!
//! Provenance vocabulary: `importée` (taken from world.db), `ofm-générée` (OFM's own value kept).
//! The values in world.db's `club_finance_start` are themselves generated by the importer
//! (`source = générée`, orders of magnitude to verify): that is carried in `origin`, never hidden.

use crate::config::Config;
use crate::journal::Journal;
use crate::source::ClubRow;
use domain::team::Team;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Provenance {
    Imported,
    OfmGenerated,
}

impl Provenance {
    pub fn label(&self) -> &'static str {
        match self {
            Self::Imported => "importée",
            Self::OfmGenerated => "ofm-générée",
        }
    }
}

#[derive(Debug, Clone)]
pub struct FinanceRecord {
    pub club_id: i64,
    pub field: &'static str,
    pub value: i64,
    pub provenance: Provenance,
    /// Where the value came from before the adapter (`générée` by the importer, `save`, or `OFM`).
    pub origin: String,
    pub note: String,
}

/// Restores the finance fields on a built team. `weekly_wage_bill_eur` is the wage bill of the
/// imported players the club kept (OFM's generated fillers excluded).
pub fn restore(
    team: &mut Team,
    club: &ClubRow,
    weekly_wage_bill_eur: i64,
    cfg: &Config,
    journal: &mut Journal,
) -> Vec<FinanceRecord> {
    let mut records = Vec::new();
    let Some(finance) = &club.finance else {
        journal.warn(
            "finance.missing",
            &team.id,
            "no club_finance_start row; OFM's values are kept",
        );
        for field in ["balance", "transfer_budget", "wage_budget"] {
            records.push(FinanceRecord {
                club_id: club.id,
                field: static_field(field),
                value: match field {
                    "balance" => team.finance,
                    "transfer_budget" => team.transfer_budget,
                    _ => team.wage_budget,
                },
                provenance: Provenance::OfmGenerated,
                origin: "OFM".into(),
                note: "no source row".into(),
            });
        }
        return records;
    };
    let origin = finance.source.clone();

    if cfg.finance.restore_balance {
        team.finance = cfg.to_eur(finance.balance_gbp);
    }
    records.push(FinanceRecord {
        club_id: club.id,
        field: "balance",
        value: team.finance,
        provenance: Provenance::Imported,
        origin: origin.clone(),
        note: String::new(),
    });

    if cfg.finance.restore_transfer_budget {
        team.transfer_budget = cfg.to_eur(finance.transfer_budget_gbp);
    }
    records.push(FinanceRecord {
        club_id: club.id,
        field: "transfer_budget",
        value: team.transfer_budget,
        provenance: Provenance::Imported,
        origin: origin.clone(),
        note: String::new(),
    });

    let source_wage_budget = cfg.to_eur(finance.wage_budget_gbp_week);
    if cfg.finance.restore_wage_budget
        && source_wage_budget > 0
        && source_wage_budget >= weekly_wage_bill_eur
    {
        team.wage_budget = source_wage_budget;
        records.push(FinanceRecord {
            club_id: club.id,
            field: "wage_budget",
            value: source_wage_budget,
            provenance: Provenance::Imported,
            origin,
            note: String::new(),
        });
    } else {
        let note = if source_wage_budget <= 0 {
            "source wage budget is 0".to_string()
        } else {
            format!(
                "source wage budget {source_wage_budget} is below the imported wage bill {weekly_wage_bill_eur}"
            )
        };
        journal.warn(
            "finance.wage_budget_incompatible",
            &team.id,
            format!("{note}; OFM's value is kept"),
        );
        records.push(FinanceRecord {
            club_id: club.id,
            field: "wage_budget",
            value: team.wage_budget,
            provenance: Provenance::OfmGenerated,
            origin: "OFM".into(),
            note,
        });
    }

    records.push(FinanceRecord {
        club_id: club.id,
        field: "stadium_capacity",
        value: i64::from(team.stadium_capacity),
        provenance: Provenance::OfmGenerated,
        origin: "OFM (absente de world.db)".into(),
        note: "drawn by OFM from the build seed".into(),
    });
    records
}

fn static_field(name: &str) -> &'static str {
    match name {
        "balance" => "balance",
        "transfer_budget" => "transfer_budget",
        _ => "wage_budget",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::source::Finance;

    fn club(finance: Option<Finance>) -> ClubRow {
        ClubRow {
            id: 1,
            fm_uid: None,
            name: "X".into(),
            short_name: "X".into(),
            nation: Some("France".into()),
            reputation: 5000,
            competition_id: 12,
            colours: None,
            finance,
        }
    }

    fn finance(wage_budget: i64) -> Finance {
        Finance {
            balance_gbp: 1_000_000,
            transfer_budget_gbp: 200_000,
            wage_budget_gbp_week: wage_budget,
            wage_bill_gbp_week: 50_000,
            tv_gbp: 0,
            other_revenue_gbp: 0,
            other_costs_gbp: 0,
            source: "générée".into(),
        }
    }

    fn team() -> Team {
        Team::new(
            "fm-c-1".into(),
            "X".into(),
            "X".into(),
            "FR".into(),
            "Paris".into(),
            "Stade".into(),
            20_000,
        )
    }

    #[test]
    fn compatible_values_are_restored_in_euros() {
        let cfg = Config::default_config();
        let mut t = team();
        let mut journal = Journal::default();
        let records = restore(
            &mut t,
            &club(Some(finance(100_000))),
            90_000,
            &cfg,
            &mut journal,
        );
        assert_eq!(t.finance, 1_170_000);
        assert_eq!(t.transfer_budget, 234_000);
        assert_eq!(t.wage_budget, 117_000);
        assert!(
            records
                .iter()
                .any(|r| r.field == "wage_budget" && r.provenance == Provenance::Imported)
        );
        assert!(
            records
                .iter()
                .any(|r| r.field == "stadium_capacity" && r.provenance == Provenance::OfmGenerated)
        );
    }

    #[test]
    fn a_wage_budget_below_the_wage_bill_is_not_restored() {
        let cfg = Config::default_config();
        let mut t = team();
        t.wage_budget = 77_000;
        let mut journal = Journal::default();
        let records = restore(
            &mut t,
            &club(Some(finance(10_000))),
            90_000,
            &cfg,
            &mut journal,
        );
        assert_eq!(t.wage_budget, 77_000);
        let record = records.iter().find(|r| r.field == "wage_budget").unwrap();
        assert_eq!(record.provenance, Provenance::OfmGenerated);
        assert_eq!(journal.count("finance.wage_budget_incompatible"), 1);
    }

    #[test]
    fn a_zero_wage_budget_is_not_restored() {
        let cfg = Config::default_config();
        let mut t = team();
        t.wage_budget = 5_000;
        let mut journal = Journal::default();
        restore(&mut t, &club(Some(finance(0))), 0, &cfg, &mut journal);
        assert_eq!(t.wage_budget, 5_000);
    }

    #[test]
    fn a_club_without_a_finance_row_keeps_ofms_values_and_says_so() {
        let cfg = Config::default_config();
        let mut t = team();
        let before = t.finance;
        let mut journal = Journal::default();
        let records = restore(&mut t, &club(None), 0, &cfg, &mut journal);
        assert_eq!(t.finance, before);
        assert!(
            records
                .iter()
                .all(|r| r.provenance == Provenance::OfmGenerated)
        );
        assert_eq!(journal.count("finance.missing"), 1);
    }
}
