//! The competition profiles that ship: their shape and their 2026/27 calendars.
//!
//! **Provenance, kept next to the data it qualifies.** All three calendars are the dates UEFA
//! published for 2026/27 ("subject to change"): the Champions League page of 4 November 2026, the
//! Europa League and Conference League pages of 23 November 2026. (EUROPE4 derived the second and
//! third from the Champions League week; INTEGRATION5 replaced that with the published dates.)
//! Nothing here is a fixture list: UEFA publishes which clubs play on which day after the draw,
//! and this game never imports that.

