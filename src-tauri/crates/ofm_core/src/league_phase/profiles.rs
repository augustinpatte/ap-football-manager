//! The competition profiles that ship: their shape and their 2026/27 calendars.
//!
//! **Provenance, kept next to the data it qualifies.** The Champions League dates are the ones
//! UEFA published for 2026/27 ("subject to change"). The Europa League and Conference League dates
//! were not on the pages read: they are *derived* (the Thursday of the Champions League week), and
//! the two finals are placeholders. Nothing here is a fixture list: UEFA publishes which clubs play
//! on which day after the draw, and this game never imports that.

use domain::league_phase::{
    ContinentalPrize, KnockoutStage, KnockoutWindow, LeaguePhaseCalendar, LeaguePhaseRules,
};

const CL_LEAGUE_MATCHDAYS: [&[&str]; 8] = [
    &["2026-09-08", "2026-09-09", "2026-09-10"],
    &["2026-10-13", "2026-10-14"],
    &["2026-10-20", "2026-10-21"],
    &["2026-11-03", "2026-11-04"],
    &["2026-11-24", "2026-11-25"],
    &["2026-12-08", "2026-12-09"],
    &["2027-01-19", "2027-01-20"],
    &["2027-01-27"],
];

/// `(stage, first-leg dates, second-leg dates)` for the Champions League.
const CL_KNOCKOUT: [(KnockoutStage, &[&str], &[&str]); 5] = [
    (
        KnockoutStage::Playoffs,
        &["2027-02-16", "2027-02-17"],
        &["2027-02-23", "2027-02-24"],
    ),
    (
        KnockoutStage::RoundOf16,
        &["2027-03-09", "2027-03-10"],
        &["2027-03-16", "2027-03-17"],
    ),
    (
        KnockoutStage::QuarterFinals,
        &["2027-04-06", "2027-04-07"],
        &["2027-04-13", "2027-04-14"],
    ),
    (
        KnockoutStage::SemiFinals,
        &["2027-04-27", "2027-04-28"],
        &["2027-05-04", "2027-05-05"],
    ),
    (KnockoutStage::Final, &["2027-06-05"], &[]),
];

/// The Thursday of the Champions League week that holds `date`: how the Europa and Conference
/// League dates are derived.
///
/// A date that cannot be read or moved is returned unchanged: the template dates are literals in
/// this file, and `edition_dates` refuses an unreadable one with a typed error anyway.
fn thursday_of(date: &str) -> String {
    use chrono::{Datelike, Days, NaiveDate};
    let Ok(day) = NaiveDate::parse_from_str(date, "%Y-%m-%d") else {
        return date.to_string();
    };
    let to_thursday = (3 + 7 - i64::from(day.weekday().num_days_from_monday())) % 7;
    day.checked_add_days(Days::new(to_thursday as u64))
        .map_or_else(
            || date.to_string(),
            |moved| moved.format("%Y-%m-%d").to_string(),
        )
}

fn strings(dates: &[&str]) -> Vec<String> {
    dates.iter().map(|date| (*date).to_string()).collect()
}

fn champions_league_calendar() -> LeaguePhaseCalendar {
    LeaguePhaseCalendar {
        template_version: 1,
        reference_season: 2026,
        provenance: "UEFA 2026/27 Champions League dates as published (subject to change); \
                     other seasons are generated by whole-week shifts, never official."
            .to_string(),
        league_matchdays: CL_LEAGUE_MATCHDAYS.iter().map(|day| strings(day)).collect(),
        knockout_windows: CL_KNOCKOUT
            .iter()
            .map(|(stage, first, second)| KnockoutWindow {
                stage: *stage,
                first_leg: strings(first),
                second_leg: strings(second),
            })
            .collect(),
    }
}

/// Thursday version of the Champions League calendar for the other two competitions. `matchdays`
/// takes that many leading Champions League weeks; `final_date` replaces the Champions League
/// final.
fn thursday_calendar(matchdays: usize, final_date: &str) -> LeaguePhaseCalendar {
    let mut calendar = champions_league_calendar();
    calendar.provenance = "DERIVED, not published: the Thursday of the 2026/27 Champions League \
                           week; the final date is a placeholder."
        .to_string();
    calendar.league_matchdays = CL_LEAGUE_MATCHDAYS
        .iter()
        .take(matchdays)
        .filter_map(|day| day.last())
        .map(|last| vec![thursday_of(last)])
        .collect();
    for window in &mut calendar.knockout_windows {
        if window.stage == KnockoutStage::Final {
            window.first_leg = vec![final_date.to_string()];
            continue;
        }
        let last = |dates: &[String]| dates.last().map(|date| thursday_of(date));
        window.first_leg = last(&window.first_leg).into_iter().collect();
        window.second_leg = last(&window.second_leg).into_iter().collect();
    }
    calendar
}

/// Game-balance prize money for a competition, scaled from the Champions Cup's. These are
/// assumptions chosen to sit beside the game's domestic prize money; they are **not** UEFA's
/// published distribution and carry no regulatory weight.
fn balance_prize(scale_percent: i64) -> ContinentalPrize {
    let scaled = |amount: i64| amount * scale_percent / 100;
    ContinentalPrize {
        participation: scaled(2_000_000),
        per_win: scaled(400_000),
        per_draw: scaled(130_000),
        // Reaching the play-offs, round of 16, quarter-finals, semi-finals and final.
        per_stage_reached: [300_000, 1_000_000, 1_500_000, 2_500_000, 4_000_000]
            .into_iter()
            .map(scaled)
            .collect(),
        champion: scaled(3_000_000),
    }
}

/// UEFA Champions League 2026/27: 36 clubs, 4 pots of 9, 8 matches.
pub fn champions_league_2026() -> LeaguePhaseRules {
    LeaguePhaseRules {
        calendar: champions_league_calendar(),
        prize: balance_prize(100),
        ..LeaguePhaseRules::four_pots_of_nine()
    }
}

/// UEFA Europa League 2026/27: the Champions League shape; calendar derived.
pub fn europa_league_2026() -> LeaguePhaseRules {
    LeaguePhaseRules {
        calendar: thursday_calendar(8, "2027-05-19"),
        prize: balance_prize(40),
        ..LeaguePhaseRules::four_pots_of_nine()
    }
}

/// UEFA Conference League 2026/27: 36 clubs, 6 pots of 6, 6 matches; calendar derived.
pub fn conference_league_2026() -> LeaguePhaseRules {
    LeaguePhaseRules {
        calendar: thursday_calendar(6, "2027-05-26"),
        prize: balance_prize(20),
        ..LeaguePhaseRules::six_pots_of_six()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Given the three shipped profiles
    /// When each is validated
    /// Then each has the regulation shape and a calendar of the right length.
    #[test]
    fn every_shipped_profile_is_valid() {
        for rules in [
            champions_league_2026(),
            europa_league_2026(),
            conference_league_2026(),
        ] {
            assert_eq!(rules.validate(), Ok(()));
            assert_eq!(
                rules.calendar.league_matchdays.len(),
                rules.matches_per_club()
            );
            assert_eq!(rules.calendar.knockout_windows.len(), 5);
            assert!(!rules.calendar.provenance.is_empty());
        }
    }

    /// Given the derived Thursday calendars
    /// When their dates are read
    /// Then every league-phase date is a Thursday and labelled as derived.
    #[test]
    fn derived_calendars_are_thursdays_and_say_they_are_derived() {
        use chrono::{Datelike, NaiveDate, Weekday};
        for rules in [europa_league_2026(), conference_league_2026()] {
            assert!(rules.calendar.provenance.starts_with("DERIVED"));
            for date in rules.calendar.league_matchdays.iter().flatten() {
                let parsed = NaiveDate::parse_from_str(date, "%Y-%m-%d").unwrap();
                assert_eq!(parsed.weekday(), Weekday::Thu, "{date}");
            }
        }
    }
}
